pub fn tr(lang: Lang, key: &str) -> &'static str {
    for (k, en, fr) in TABLE {
        if *k == key {
            return match lang {
                Lang::En => en,
                Lang::Fr => fr,
            };
        }
    }
    // Unknown keys are a programming error; show something readable.
    Box::leak(key.to_string().into_boxed_str())
}

/// Both translations of a key (the slash menu matches either language).
pub fn both(key: &str) -> (&'static str, &'static str) {
    TABLE.iter().find(|(k, _, _)| *k == key).map(|(_, en, fr)| (*en, *fr)).unwrap_or(("", ""))
}

